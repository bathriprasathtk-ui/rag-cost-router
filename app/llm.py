"""LLM clients: an OpenAI-compatible chat client (works with Groq, OpenAI,
Together, vLLM, ...) plus an offline mock provider, and cost accounting shared
by both.
"""
from __future__ import annotations

import time
from dataclasses import dataclass

import httpx

from . import config


@dataclass
class LLMResult:
    text: str
    model: str
    prompt_tokens: int
    completion_tokens: int
    latency_ms: float
    cost_usd: float
    refusal: bool = False


def estimate_tokens(text: str) -> int:
    """~4 chars/token approximation, used when the provider returns no usage."""
    return max(1, len(text) // 4)


def compute_cost(model: str, prompt_tokens: int, completion_tokens: int) -> float:
    price = config.price_for(model)
    return (prompt_tokens * price["input"] + completion_tokens * price["output"]) / 1_000_000


_REFUSAL_MARKERS = (
    "i don't know", "i do not know", "i'm not sure", "i am not sure",
    "cannot answer", "can't answer", "no information", "as an ai",
    # MockLLM's punt (and real small models) hedge instead of saying "I don't know".
    "not confident",
)


def looks_like_refusal(text: str) -> bool:
    low = text.lower()
    return any(marker in low for marker in _REFUSAL_MARKERS) or len(text.strip()) < 40


class LLMClient:
    """OpenAI-compatible /chat/completions client.

    Any provider exposing the OpenAI API shape works: Groq, OpenAI, Together,
    Fireworks, vLLM, LiteLLM, ...
    """

    def __init__(self, provider: str = config.PROVIDER):
        self.provider = provider
        self.api_key = config.LLM_API_KEY
        self.base_url = config.LLM_BASE_URL

    @property
    def available(self) -> bool:
        return bool(self.api_key and self.base_url)

    async def complete(self, model: str, system: str, user: str, max_tokens: int = 1400) -> LLMResult:
        payload = {
            "model": model,
            "messages": [
                {"role": "system", "content": system},
                {"role": "user", "content": user},
            ],
            "temperature": 0.2,
            "max_tokens": max_tokens,
        }
        started = time.perf_counter()
        async with httpx.AsyncClient(timeout=60) as client:
            resp = await client.post(
                f"{self.base_url}/chat/completions",
                headers={"Authorization": f"Bearer {self.api_key}"},
                json=payload,
            )
            resp.raise_for_status()
        data = resp.json()
        latency_ms = (time.perf_counter() - started) * 1000

        text = data["choices"][0]["message"]["content"] or ""
        usage = data.get("usage") or {}
        prompt_tokens = usage.get("prompt_tokens") or estimate_tokens(system + user)
        completion_tokens = usage.get("completion_tokens") or estimate_tokens(text)
        return LLMResult(
            text=text,
            model=data.get("model", model),
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            latency_ms=latency_ms,
            cost_usd=compute_cost(model, prompt_tokens, completion_tokens),
            refusal=looks_like_refusal(text),
        )


class MockLLM:
    """Deterministic offline provider so the dashboard and tests run without keys.

    Honors the routing contract: the small model answers shallow questions well
    but punts on multi-hop reasoning, which is exactly what triggers escalation.
    """

    name = "mock"

    def __init__(self, embedder=None):
        self.embedder = embedder

    async def complete(self, model: str, system: str, user: str, max_tokens: int = 1400) -> LLMResult:
        started = time.perf_counter()
        question = user.split("Question:", 1)[-1].strip().split("\n")[0]
        context = ""
        if "Context:" in user:
            context = user.split("Context:", 1)[1].split("Question:", 1)[0].strip()

        is_large = model in {config.LARGE_MODEL, "mock-large"} or "70b" in model or "large" in model
        hard = self._is_hard(question)

        # Simulated per-tier latency: large models take longer.
        await _sleep(0.35 if is_large else 0.08)

        if hard and not is_large:
            text = (
                "I'm not confident I can fully answer that from the provided context. "
                "It requires connecting several pieces of information."
            )
        elif context:
            lead = "Synthesizing across sources: " if is_large else "Based on the context: "
            snippet = " ".join(context.split())[:400]
            text = f"{lead}{snippet} — regarding '{question}', the documents indicate the above is the key evidence."
        else:
            text = f"Mock answer to '{question}' generated by {model}."

        latency_ms = (time.perf_counter() - started) * 1000
        prompt_tokens = estimate_tokens(system + user)
        completion_tokens = estimate_tokens(text)
        return LLMResult(
            text=text,
            model=model,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            latency_ms=latency_ms,
            cost_usd=compute_cost(model, prompt_tokens, completion_tokens),
            refusal=looks_like_refusal(text),
        )

    @staticmethod
    def _is_hard(question: str) -> bool:
        from .router import score_difficulty  # avoid circular import at module load

        # Punt on anything meaningfully complex — at a cutoff below the router
        # threshold, so queries the router optimistically sent to the small
        # model actually exercise the escalation path offline. The 0.2 margin
        # clears the router's biggest single bonus (retrieval spread, +0.15),
        # which the mock cannot see when it re-scores the bare question.
        cutoff = max(0.1, config.ROUTE_THRESHOLD - 0.2)
        return score_difficulty(question).difficulty >= cutoff


async def _sleep(seconds: float) -> None:
    import asyncio

    await asyncio.sleep(seconds)


def build_llm(embedder=None):
    """Return a real client when the active provider has a key, else the mock."""
    if config.PROVIDER != "mock" and config.LLM_API_KEY:
        return LLMClient(config.PROVIDER)
    return MockLLM(embedder)
